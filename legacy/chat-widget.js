// Chat Widget Functionality
class ChatWidget {
    constructor() {
        this.chatWindow = document.getElementById('chat-window');
        this.chatToggleBtn = document.getElementById('chat-toggle-btn');
        this.chatCloseBtn = document.getElementById('chat-close-btn');
        this.chatInput = document.getElementById('chat-input');
        this.chatSendBtn = document.getElementById('chat-send-btn');
        this.chatMessages = document.getElementById('chat-messages');
        this.chatSuggestions = document.getElementById('chat-suggestions');
        
        this.init();
    }
    
    init() {
        // Event listeners
        this.chatToggleBtn.addEventListener('click', () => this.toggleChat());
        this.chatCloseBtn.addEventListener('click', () => this.toggleChat());
        this.chatSendBtn.addEventListener('click', () => this.sendMessage());
        this.chatInput.addEventListener('keypress', (e) => {
            if (e.key === 'Enter') this.sendMessage();
        });
    }
    
    toggleChat() {
        this.chatWindow.classList.toggle('active');
        if (this.chatWindow.classList.contains('active')) {
            this.chatInput.focus();
        }
    }
    
    sendMessage(text = null) {
        const message = text || this.chatInput.value.trim();
        if (!message) return;
        
        // Add user message
        this.addMessage(message, 'user');
        
        // Clear input
        this.chatInput.value = '';
        
        // Hide suggestions after first message
        if (this.chatSuggestions) {
            this.chatSuggestions.style.display = 'none';
        }
        
        // Show typing indicator
        this.showTypingIndicator();
        
        // Process message and get response
        setTimeout(() => {
            this.removeTypingIndicator();
            const response = this.getAIResponse(message);
            this.addMessage(response, 'bot');
        }, 1000 + Math.random() * 1000); // Random delay for realism
    }
    
    addMessage(text, type) {
        const messageDiv = document.createElement('div');
        messageDiv.className = `message ${type}`;
        messageDiv.textContent = text;
        this.chatMessages.appendChild(messageDiv);
        this.chatMessages.scrollTop = this.chatMessages.scrollHeight;
    }
    
    showTypingIndicator() {
        const typingDiv = document.createElement('div');
        typingDiv.className = 'message-typing';
        typingDiv.id = 'typing-indicator';
        typingDiv.innerHTML = `
            <div class="typing-dot"></div>
            <div class="typing-dot"></div>
            <div class="typing-dot"></div>
        `;
        this.chatMessages.appendChild(typingDiv);
        this.chatMessages.scrollTop = this.chatMessages.scrollHeight;
    }
    
    removeTypingIndicator() {
        const typingIndicator = document.getElementById('typing-indicator');
        if (typingIndicator) {
            typingIndicator.remove();
        }
    }
    
    getAIResponse(message) {
        const lowerMessage = message.toLowerCase();
        
        // Search through knowledge base
        for (const category in cybersecurityKnowledgeBase) {
            const data = cybersecurityKnowledgeBase[category];
            const hasKeyword = data.keywords.some(keyword => 
                lowerMessage.includes(keyword.toLowerCase())
            );
            
            if (hasKeyword) {
                // Return random answer from category
                const randomIndex = Math.floor(Math.random() * data.answers.length);
                return data.answers[randomIndex];
            }
        }
        
        // Default responses if no match found
        const defaultResponses = [
            "Разбирам въпроса ви. За по-детайлна информация и персонализирано решение, моля свържете се с нашия екип на info@defcoms.eu или +359 886 088 668.",
            "Това е интересен въпрос за киберсигурността. За експертна консултация, моля използвайте формата за контакт или ни се обадете.",
            "Благодаря за въпроса! За пълна оценка на вашите нужди се свържете с нас – консултацията е платена и се определя според обема и конкретната задача; безплатна е само първоначалната консултация по имейл.",
            "Въпросът ви е важен за киберсигурността. Свържете се с нас за персонализирано решение."
        ];
        
        return defaultResponses[Math.floor(Math.random() * defaultResponses.length)];
    }
}

